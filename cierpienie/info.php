        Szachy to jedna z najstarszych i najpopularniejszych gier planszowych na świecie. <br>
          <h4>Czym są szachy?</h4>
          Szachy to gra planszowa, w której dwóch graczy rozgrywa bitwę pomiędzy dwiema armiami. Jest to jedna z najpopularniejszych gier na świecie. Miliony entuzjastów grają w nią zarówno rekreacyjnie, jak i turniejowo. <br>
         Przeciwnicy dysponują zestawami bierek w odmiennych kolorach. W skład każdego z nich wchodzi szesnaście bierek: król, hetman (potocznie zwany też damą, damką, królową lub królówką), dwa gońce (z niemieckiego nazywane czasami lauframi), dwa skoczki (zwane też popularnie końmi lub konikami), dwie wieże oraz osiem pionów (pionków). <br>

Wartość figur szachowych może być absolutna lub względna. Przy założeniu, że wartość absolutna piona wynosi 1, względne wartości statyczne figur przedstawiają się następująco[3][4]: hetman – 9 punktów, wieża – 5 punktów, goniec – 3 punkty, skoczek – 3 punkty, król – nie ma przypisanej wartości ze względu na to, że nie można go wymienić, ale jego siłę szacuje się na około 4 punktów (od 3,5[5] do 5[6]). <br>
   Grę zawsze rozpoczynają białe, co daje im pewną inicjatywę w początkowej fazie partii. Gracze na zmianę wykonują posunięcia swoimi bierkami zgodnie z zasadami ruchu dla danej bierki i jeśli wejdzie ona na pole zajmowane przez przeciwnika, zbija jego bierkę. <br>

Szach jest groźbą zbicia króla, która musi być zażegnana przez przeciwnika w następnym posunięciu (króla nie można zbić). Mat, czyli postawienie króla przeciwnika w szachu, przed którym nie ma obrony, kończy partię i oznacza zwycięstwo gracza, którego bierka matuje króla przeciwnika. Remis występuje w przypadku, gdy: <br>

1. gracze uzgodnili taki wynik partii, <br>
2. na planszy wystąpił pat (jedna ze stron nie może wykonać prawidłowych posunięć, a jej król nie jest szachowany), <br>
3. żadna ze stron nie posiada środków niezbędnych do wygranej (choćby teoretycznej), <br>
4. powstała martwa pozycja, czyli żaden z graczy nie jest w stanie dać mata nawet przy najlepszej grze. <br>
5. Partia może zakończyć się remisem (na wniosek jednej ze stron), gdy: <br>
6. identyczna pozycja na planszy pojawiła się trzykrotnie, <br>
7. jedna ze stron daje wiecznego szacha, <br>
8. wykonano pięćdziesiąt posunięć bez ruchu pionem i bicia dowolną bierką. <br>
